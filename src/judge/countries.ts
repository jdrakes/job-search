// The place names behind the "United States only" rule. One set of names
// for both criteria (`country` in listing.ts reads the label,
// `country_restriction` in text.ts the body): a name on one list and
// missing from the other would let the same posting read as foreign by its
// label and domestic by its text. In code, not the criteria row, since the
// world's country names are not James's to set.
//
// The United States list can afford to be loose: it is consulted only after
// a foreign name has matched, and only ever to keep a posting. A false hit
// there costs one glance; a false hit on the foreign list loses a role.

function escapeRegExp(term: string): string {
  return term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// A term written in capitals is an acronym and matches only in capitals;
// otherwise "US" matches the pronoun and "EU", "IN" and "OK" match
// ordinary words.
function patternFor(term: string): RegExp {
  const isAcronym = term === term.toUpperCase() && /[A-Z]/.test(term);
  return new RegExp(`\\b${escapeRegExp(term)}\\b`, isAcronym ? "" : "i");
}

// "U.S." and "U.S.A." are "US" and "USA" once the dots go, and no name
// below carries one. `\b` will not close a match on a trailing ".".
function normalize(text: string): string {
  return text.replace(/\./g, "");
}

