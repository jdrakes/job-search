const FOREIGN_PATTERNS: readonly (readonly [string, RegExp])[] = [
  ...COUNTRY_TERMS,
  ...FOREIGN_REGION_TERMS,
].map((term) => [term, patternFor(term)] as const);

const UNITED_STATES_PATTERNS: readonly (readonly [string, RegExp])[] = UNITED_STATES_TERMS.map(
  (term) => [term, patternFor(term)] as const,
);

function firstMatch(text: string, patterns: readonly (readonly [string, RegExp])[]): string | null {
  const normalized = normalize(text);
  for (const [term, pattern] of patterns) {
    if (pattern.test(normalized)) return term;
  }
  return null;
}

// Null is the design's default case, "a posting that names no country is
// in", not an error.
export function foreignPlace(text: string): string | null {
  return firstMatch(text, FOREIGN_PATTERNS);
}

// A text naming both ("Remote US & Canada") is in, so a foreign match is
// checked against this rather than overturned by it.
export function unitedStatesPlace(text: string): string | null {
  return firstMatch(text, UNITED_STATES_PATTERNS);
}
